// --- DATA PATH OPERATIONS --- //

inline void add_round_tweakey(uint8_t state[8], const uint8_t rk[8]) {
    for (int i = 0; i < 8; i++) {
        state[i] = (state[i] ^ rk[i]) & 0x0F;
    }
}

inline void sub_cells(uint8_t state[8]) {
    for (int i = 0; i < 8; i++) {
        state[i] = SBOX[state[i] & 0x0F];
    }
}

inline void shift_rows(uint8_t state[8]) {
    uint8_t temp[8];
    temp[0] = state[0];
    temp[1] = state[5];
    temp[2] = state[2];
    temp[3] = state[7];
    temp[4] = state[4];
    temp[5] = state[1];
    temp[6] = state[6];
    temp[7] = state[3];
    for (int i = 0; i < 8; i++) {
        state[i] = temp[i];
    }
}

inline void mix_columns(uint8_t state[8]) {
    uint8_t temp[8];
    for (int i = 0; i < 8; i++) temp[i] = state[i];

    for (int col = 0; col < 2; col++) {
        int base = col * 4;
        for (int r = 0; r < 4; r++) {
            uint8_t val = 0;
            for (int c = 0; c < 4; c++) {
                val ^= GF_MUL_TABLE[MDS_MATRIX[r][c]][temp[base + c]];
            }
            state[base + r] = val & 0x0F;
        }
    }
}

inline void beanie_encrypt(uint8_t state[8], const uint8_t round_keys[ROUNDS + 1][8]) {
    for (int r = 0; r < ROUNDS - 1; r++) {
        add_round_tweakey(state, round_keys[r]);
        sub_cells(state);
        shift_rows(state);
        mix_columns(state);
    }
    add_round_tweakey(state, round_keys[ROUNDS - 1]);
    sub_cells(state);
    shift_rows(state);
    add_round_tweakey(state, round_keys[ROUNDS]);
}

// --- TWEAK-KEY SCHEDULE DERIVATION USING TKS.H --- //

inline void derive_round_keys(const uint8_t key[32], const uint8_t tweak[32], uint8_t round_keys[ROUNDS + 1][8]) {
    alignas(16) uint64_t k_w[2] = {0, 0}, tw_w[2] = {0, 0};
    for (int i = 0; i < 16; i++) {
        k_w[1]  |= ((uint64_t)(key[i] & 0x0F) << (4 * (15 - i)));
        k_w[0]  |= ((uint64_t)(key[16 + i] & 0x0F) << (4 * (15 - i)));
        tw_w[1] |= ((uint64_t)(tweak[i] & 0x0F) << (4 * (15 - i)));
        tw_w[0] |= ((uint64_t)(tweak[16 + i] & 0x0F) << (4 * (15 - i)));
    }

    __m128i key128   = _mm_load_si128((const __m128i*)k_w);
    __m128i tweak128 = _mm_load_si128((const __m128i*)tw_w);

    // Call SIMD tweak_key_schedule from tks.h
    __m128i tks_state128 = tweak_key_schedule(key128, tweak128, ROUNDS);

    alignas(16) uint64_t res_w[2];
    _mm_store_si128((__m128i*)res_w, tks_state128);

    uint8_t state[32];
    for (int i = 0; i < 16; i++) {
        state[i]      = (res_w[1] >> (4 * (15 - i))) & 0x0F;
        state[16 + i] = (res_w[0] >> (4 * (15 - i))) & 0x0F;
    }

    for (int k = 0; k < 4 && k <= ROUNDS; k++) {
        for (int i = 0; i < 8; i++) {
            round_keys[k][i] = state[k * 8 + i];
        }
    }
    if (ROUNDS >= 4) {
        for (int i = 0; i < 8; i++) {
            round_keys[4][i] = round_keys[0][i] ^ round_keys[1][i];
        }
    }
    if (ROUNDS >= 5) {
        for (int i = 0; i < 8; i++) {
            round_keys[5][i] = round_keys[2][i] ^ round_keys[3][i];
        }
    }
}

// Oracle function accepting message, key, tweak key, and returning ciphertext
inline void oracle(const uint8_t message[8], const uint8_t key[32], const uint8_t tweak[32], uint8_t ciphertext[8]) {
    // 1. Dynamically derive round keys using SIMD TKS
    uint8_t round_keys[ROUNDS + 1][8];
    derive_round_keys(key, tweak, round_keys);

    // 2. Encrypt plaintext message state
    uint8_t state[8];
    for (int i = 0; i < 8; i++) {
        state[i] = message[i] & 0x0F;
    }

    beanie_encrypt(state, round_keys);

    for (int i = 0; i < 8; i++) {
        ciphertext[i] = state[i] & 0x0F;
    }
}

